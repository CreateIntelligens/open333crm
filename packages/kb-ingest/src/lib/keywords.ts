/** 扁平化所有關鍵詞（供快速 any-match）。 */
export const ALL_KEYWORDS: string[] = Object.values(GAP_KEYWORDS).flat();

/**
 * 判斷一段文字命中哪些缺口分類。
 * 回傳命中的分類清單（去重）。
 */
export function matchGapCategories(text: string): string[] {
  const hits = new Set<string>();
  for (const [category, words] of Object.entries(GAP_KEYWORDS)) {
    if (words.some((w) => text.includes(w))) hits.add(category);
  }
  return [...hits];
}
